import type { Finding, QaCheckStatus, Verdict } from "@zastava/contracts";

/** Shown at the bottom of every PR and delivery commit. */
export const SIGNATURE = "Generated by ZASTAVA";
/** GitHub caps PR bodies at 65,536 chars; stay well under it. */
const MAX_BODY_CHARS = 60_000;
const MAX_SUMMARY_CHARS = 6_000;
const MAX_STAT_LINES = 60;

export interface PrStation {
  name: string;
  kind: "agent" | "gate" | "checks" | "shift" | "qa";
  status: string;
  attempts: number;
  model: string | null;
  costUsd: number;
  /** Shift stations only. */
  shifts: number | null;
}

export interface PrBodyInput {
  description: string;
  /** What the building station reported at the end (agent prose, usually markdown). */
  summary: string | null;
  diffStat: string;
  verdict: Verdict | null;
  stations: PrStation[];
  /** True when any station billed a subscription (costs are estimates). */
  estimated: boolean;
  /** The last QA attempt, when the line has a QA station. */
  qa?: PrQa | null;
}

export interface PrQa {
  status: "running" | "passed" | "failed" | "error";
  attempts: number;
  summary: string | null;
  checks: {
    name: string;
    kind: string;
    status: QaCheckStatus;
    path: string | null;
    viewport: string | null;
    theme: string | null;
    /** Accepted as intended by a human in ZASTAVA. */
    accepted: boolean;
  }[];
}

const QA_STATUS_LABEL: Record<QaCheckStatus, string> = {
  fail: "❌ fail",
  error: "⚠️ error",
  changed: "🔶 changed",
  intended: "✅ intended",
  pass: "✅ pass",
};
const QA_ORDER: QaCheckStatus[] = ["fail", "error", "changed", "intended", "pass"];
const MAX_QA_ROWS = 40;

function renderQa(qa: PrQa): string {
  const counts = QA_ORDER.flatMap((status) => {
    const n = qa.checks.filter((c) => c.status === status).length;
    return n ? [`${n} ${status}`] : [];
  }).join(" · ");
  const head = `**${qa.status === "passed" ? "✅ Pass" : qa.status === "failed" ? "❌ Fail" : "⚠️ Error"}**${qa.attempts > 1 ? ` after ${qa.attempts} attempts` : ""}${counts ? ` — ${counts}` : ""}${qa.summary ? `\n\n${qa.summary}` : ""}`;
  const sorted = qa.checks.toSorted(
    (a, b) => QA_ORDER.indexOf(a.status) - QA_ORDER.indexOf(b.status),
  );
  const rows = sorted.slice(0, MAX_QA_ROWS).map((c) => {
    const where = [c.path ? `\`${c.path}\`` : "", c.viewport, c.theme].filter(Boolean).join(" · ");
    return `| ${QA_STATUS_LABEL[c.status]}${c.accepted ? " (accepted)" : ""} | ${c.name.replace(/\|/g, "\\|")} | ${c.kind} | ${where} |`;
  });
  const more =
    sorted.length > MAX_QA_ROWS ? [`| | … ${sorted.length - MAX_QA_ROWS} more | | |`] : [];
  return [
    head,
    rows.length
      ? ["| Result | Check | Kind | Where |", "|---|---|---|---|", ...rows, ...more].join("\n")
      : "",
    "<sub>Before/after screenshots are in ZASTAVA.</sub>",
  ]
    .filter(Boolean)
    .join("\n\n");
}

const SEVERITY_ORDER: Finding["severity"][] = ["critical", "important", "minor"];

function trimTo(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max).trimEnd()}\n\n…(truncated)` : text;
}

function fence(text: string, lang = ""): string {
  // A body containing ``` would close the fence early; use a longer one.
  const ticks = text.includes("```") ? "````" : "```";
  return `${ticks}${lang}\n${text}\n${ticks}`;
}

/** Totals up front; the per-file list collapsed (GitHub's Files tab has the details). */
function renderStat(stat: string): string {
  const lines = stat.trimEnd().split("\n");
  const totals = (lines.at(-1) ?? "").trim();
  const files = lines.slice(0, -1);
  const shown =
    files.length <= MAX_STAT_LINES
      ? files
      : [...files.slice(0, MAX_STAT_LINES), ` … ${files.length - MAX_STAT_LINES} more`];
  return `${totals}\n\n<details><summary>Files</summary>\n\n${fence(shown.join("\n"))}\n\n</details>`;
}

function renderVerdict(verdict: Verdict): string {
  const head = `**${verdict.verdict === "pass" ? "✅ Pass" : "❌ Fail"}** — ${verdict.summary}`;
  if (verdict.findings.length === 0) return head;
  const groups = SEVERITY_ORDER.flatMap((severity) => {
    const items = verdict.findings.filter((f) => f.severity === severity);
    if (items.length === 0) return [];
    const list = items
      .map((f) => `- ${f.file ? `\`${f.file}\` — ` : ""}${f.message.replace(/\n+/g, " ")}`)
      .join("\n");
    return [`<details><summary>${severity} (${items.length})</summary>\n\n${list}\n\n</details>`];
  });
  return [head, ...groups].join("\n\n");
}

function renderPipeline(stations: PrStation[], estimated: boolean): string {
  const rows = stations.map((s) => {
    const runs =
      s.kind === "shift" && s.shifts
        ? `${s.shifts} shift${s.shifts === 1 ? "" : "s"}`
        : s.attempts > 0
          ? String(s.attempts)
          : "";
    const cost = s.kind === "gate" ? "" : `$${s.costUsd.toFixed(2)}`;
    return `| ${s.name} | ${s.status} | ${s.model ?? (s.kind === "gate" ? "human" : "—")} | ${runs} | ${cost} |`;
  });
  const total = stations.reduce((sum, s) => sum + s.costUsd, 0);
  return [
    "| Station | Result | Model | Runs | Cost |",
    "|---|---|---|---|---:|",
    ...rows,
    `| **Total** | | | | **$${total.toFixed(2)}**${estimated ? " est." : ""} |`,
  ].join("\n");
}

/**
 * Agents open their final message with chatter ("Perfect. Done: …", "Great!").
 * A PR summary starts with the change itself.
 */
export function stripFiller(text: string): string {
  const filler =
    /^\s*(?:(?:perfect|great|excellent|awesome|done|all set|all done|okay|ok|alright|sure)\s*[.!:,—-]*\s*)+/i;
  const out = text.replace(filler, "");
  return out ? out.charAt(0).toUpperCase() + out.slice(1) : text;
}

/** The pull request description: outcome first, the work order itself collapsed at the end. */
export function renderPrBody(input: PrBodyInput): string {
  const sections = [
    input.summary?.trim()
      ? `## Summary\n\n${trimTo(stripFiller(input.summary.trim()), MAX_SUMMARY_CHARS)}`
      : "",
    input.diffStat.trim() ? `## Changes\n\n${renderStat(input.diffStat)}` : "",
    input.verdict ? `## Validation\n\n${renderVerdict(input.verdict)}` : "",
    input.qa ? `## QA\n\n${renderQa(input.qa)}` : "",
    input.stations.length
      ? `## Pipeline\n\n${renderPipeline(input.stations, input.estimated)}`
      : "",
    input.description.trim()
      ? `<details><summary>Work order</summary>\n\n${fence(input.description.trim(), "text")}\n\n</details>`
      : "",
    `---\n<sub>${SIGNATURE}</sub>`,
  ].filter(Boolean);
  return trimTo(sections.join("\n\n"), MAX_BODY_CHARS);
}
